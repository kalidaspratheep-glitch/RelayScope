from rest_framework import generics
from .models import WebhookEndpoint, WebhookEvent, DeliveryAttempt
from .serializers import WebhookEndpointSerializer, WebhookEventSerializer
from rest_framework.views import APIView
from rest_framework.response import Response
from django.shortcuts import get_object_or_404
import time
import requests


class WebhookEndpointListCreateView(generics.ListCreateAPIView):
    queryset = WebhookEndpoint.objects.all()
    serializer_class = WebhookEndpointSerializer

class WebhookReceiveView(APIView):

    def post(self, request, token):
        endpoint = get_object_or_404(
            WebhookEndpoint,
            token=token,
            is_active=True
        )

        event = WebhookEvent.objects.create(
            endpoint=endpoint,
            method=request.method,
            headers=dict(request.headers),
            body=request.body.decode("utf-8", errors="replace"),
            content_type=request.content_type or ""
        )

        return Response(
            {
                "status": "received",
                "event_id": str(event.id)
            },
            status=202 #status code for accepted
        )

class WebhookEventListView(generics.ListAPIView):
    serializer_class = WebhookEventSerializer

    def get_queryset(self):
        endpoint_id = self.kwargs["endpoint_id"]

        endpoint = get_object_or_404(
            WebhookEndpoint,
            id=endpoint_id
        )

        return WebhookEvent.objects.filter(
            endpoint=endpoint
        ).order_by("-received_at")

class WebhookReplayView(APIView):

    def post(self, request, event_id):
        event = get_object_or_404(
            WebhookEvent,
            id=event_id
        )

        destination_url = event.endpoint.destination_url

        if not destination_url:
            return Response(
                {"error": "No destination URL configured"},
                status=400
            )

        attempt = DeliveryAttempt.objects.create(
            event=event
        )

        headers = dict(event.headers)

        # Remove headers that should be generated by requests.
        for header in ["Host", "Content-Length", "Connection"]:
            headers.pop(header, None)

        start_time = time.perf_counter()

        try:
            response = requests.request(
                method=event.method,
                url=destination_url,
                headers=headers,
                data=event.body.encode("utf-8"),
                timeout=10
            )

            duration = int(
                (time.perf_counter() - start_time) * 1000
            )

            attempt.status_code = response.status_code
            attempt.response_body = response.text[:10000]
            attempt.success = response.ok
            attempt.duration_ms = duration

            attempt.save()

            return Response({
                "status": "delivered" if response.ok else "failed",
                "attempt_id": str(attempt.id),
                "destination_status": response.status_code,
                "duration_ms": duration,
                "response_body": response.text[:10000]
            })

        except requests.RequestException as error:

            duration = int(
                (time.perf_counter() - start_time) * 1000
            )

            attempt.error_message = str(error)
            attempt.duration_ms = duration
            attempt.save()

            return Response({
                "status": "failed",
                "attempt_id": str(attempt.id),
                "error": str(error),
                "duration_ms": duration
            }, status=502)